function fieldZh(name) {
  if (FIELD_ZH[name]) return FIELD_ZH[name];
  let rest = String(name || "");
  const parts = [];
  while (rest) {
    let hit = "";
    let text = "";
    for (const [english, chinese] of NAME_PARTS) {
      if (rest.startsWith(english) && english.length > hit.length) {
        hit = english;
        text = chinese;
      }
    }
    if (!hit) {
      const chunk = rest.match(/^[a-z]+|^[A-Z][a-z0-9]*/);
      const word = chunk ? chunk[0] : rest[0];
      parts.push(word);
      rest = rest.slice(word.length);
      continue;
    }
    parts.push(text);
    rest = rest.slice(hit.length);
  }
  return parts.join("");
}

function translateLabel(text) {
  let value = String(text || "");
  for (const [english, chinese] of LABEL_RULES) {
    if (value.includes(english)) value = value.split(english).join(chinese);
  }
  return value.replace(/小时,\s*/g, "小时 ");
}
